"""SQLite-backed immutable artifact revisions and opaque file downloads."""

from __future__ import annotations

import json
import mimetypes
import sqlite3
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app.modules.intelligence.errors import IntelligenceError


def utc_stamp() -> str:
    return datetime.now(timezone.utc).isoformat()


def canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


class ArtifactStore:
    """Stores structured content revisions and generated bytes outside the web root."""

    def __init__(self, database_path: str | Path, file_root: str | Path):
        self.database_path = Path(database_path)
        self.file_root = Path(file_root).resolve()
        self.database_path.parent.mkdir(parents=True, exist_ok=True)
        self.file_root.mkdir(parents=True, exist_ok=True)
        with self.connection() as db:
            db.db.executescript(
                """
                CREATE TABLE IF NOT EXISTS artifacts (
                    id TEXT PRIMARY KEY,
                    project_id TEXT NOT NULL,
                    context_version INTEGER NOT NULL,
                    context_hash TEXT NOT NULL,
                    kind TEXT NOT NULL,
                    content_revision INTEGER NOT NULL,
                    producing_job_id TEXT,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS artifact_revisions (
                    artifact_id TEXT NOT NULL,
                    revision INTEGER NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    PRIMARY KEY (artifact_id, revision),
                    FOREIGN KEY (artifact_id) REFERENCES artifacts(id)
                );
                CREATE TABLE IF NOT EXISTS artifact_files (
                    id TEXT PRIMARY KEY,
                    artifact_id TEXT NOT NULL,
                    context_version INTEGER NOT NULL,
                    content_revision INTEGER NOT NULL,
                    format TEXT NOT NULL,
                    media_type TEXT NOT NULL,
                    filename TEXT NOT NULL,
                    size_bytes INTEGER NOT NULL,
                    storage_name TEXT NOT NULL,
                    producing_job_id TEXT,
                    created_at TEXT NOT NULL,
                    FOREIGN KEY (artifact_id) REFERENCES artifacts(id)
                );
                CREATE INDEX IF NOT EXISTS idx_artifacts_project ON artifacts(project_id, created_at DESC);
                CREATE INDEX IF NOT EXISTS idx_files_artifact ON artifact_files(artifact_id, created_at DESC);
                """
            )

    def connection(self):
        db = sqlite3.connect(str(self.database_path), timeout=20)
        db.row_factory = sqlite3.Row
        return _Connection(db)

    def _file_record(self, row: sqlite3.Row) -> dict[str, Any]:
        return {
            "file_id": row["id"],
            "artifact_id": row["artifact_id"],
            "context_version": row["context_version"],
            "content_revision": row["content_revision"],
            "format": row["format"],
            "media_type": row["media_type"],
            "filename": row["filename"],
            "size_bytes": row["size_bytes"],
            "created_at": row["created_at"],
            "download_url": f"/api/v1/files/{row['id']}/download",
        }

    def _save_bytes(self, data: bytes, suffix: str) -> tuple[str, int]:
        file_id = f"f_{uuid.uuid4().hex}"
        extension = suffix.lower().lstrip(".")[:12] or "bin"
        storage_name = f"{file_id}.{extension}"
        target = (self.file_root / storage_name).resolve()
        if target.parent != self.file_root:
            raise IntelligenceError("FILE_STORAGE_ERROR", "Could not safely store the generated file.", 500)
        target.write_bytes(data)
        return storage_name, len(data)

    def _register_file(self, db: sqlite3.Connection, artifact_id: str, context_version: int,
                       revision: int, file: dict[str, Any], producing_job_id: str | None = None) -> str:
        data = file["data"]
        filename = Path(file["filename"]).name.strip() or "startupforge-output.bin"
        fmt = str(file["format"]).lower()
        media_type = file.get("media_type") or mimetypes.guess_type(filename)[0] or "application/octet-stream"
        storage_name, size = self._save_bytes(data, Path(filename).suffix or fmt)
        file_id = f"f_{uuid.uuid4().hex}"
        db.execute(
            "INSERT INTO artifact_files VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (file_id, artifact_id, context_version, revision, fmt, media_type, filename,
             size, storage_name, producing_job_id, utc_stamp()),
        )
        return file_id

    def create_artifact(self, context, kind: str, content: dict[str, Any], files: list[dict[str, Any]]) -> tuple[str, list[str]]:
        artifact_id = f"a_{uuid.uuid4().hex}"
        now = utc_stamp()
        with self.connection() as wrapped:
            db = wrapped.db
            db.execute("BEGIN IMMEDIATE")
            db.execute(
                "INSERT INTO artifacts VALUES (?,?,?,?,?,?,?,?,?)",
                (artifact_id, context.project_id, context.context_version, context.content_hash,
                 kind, 1, None, now, now),
            )
            db.execute("INSERT INTO artifact_revisions VALUES (?,?,?,?)",
                       (artifact_id, 1, canonical(content), now))
            file_ids = [self._register_file(db, artifact_id, context.context_version, 1, item) for item in files]
        return artifact_id, file_ids

    def bind_job(self, artifact_ids: list[str], job_id: str) -> None:
        if not artifact_ids:
            return
        with self.connection() as wrapped:
            db = wrapped.db
            db.execute("BEGIN IMMEDIATE")
            for artifact_id in artifact_ids:
                changed = db.execute("UPDATE artifacts SET producing_job_id=? WHERE id=?", (job_id, artifact_id)).rowcount
                if changed:
                    db.execute("UPDATE artifact_files SET producing_job_id=? WHERE artifact_id=? AND producing_job_id IS NULL",
                               (job_id, artifact_id))

    def _manifest(self, db: sqlite3.Connection, row: sqlite3.Row) -> dict[str, Any]:
        files = db.execute("SELECT * FROM artifact_files WHERE artifact_id=? ORDER BY created_at", (row["id"],)).fetchall()
        return {
            "artifact_id": row["id"],
            "project_id": row["project_id"],
            "context_version": row["context_version"],
            "context_hash": row["context_hash"],
            "kind": row["kind"],
            "content_revision": row["content_revision"],
            "producing_job_id": row["producing_job_id"],
            "created_at": row["created_at"],
            "updated_at": row["updated_at"],
            "files": [self._file_record(file) for file in files],
        }

    def get_artifact(self, artifact_id: str) -> dict[str, Any]:
        with self.connection() as wrapped:
            db = wrapped.db
            row = db.execute("SELECT * FROM artifacts WHERE id=?", (artifact_id,)).fetchone()
            if not row:
                raise IntelligenceError("ARTIFACT_NOT_FOUND", "This generated artifact does not exist.", 404)
            return self._manifest(db, row)

    def list_artifacts(self, project_id: str, *, context_version: int | None = None,
                       kind: str | None = None, limit: int = 100) -> list[dict[str, Any]]:
        conditions = ["project_id=?"]
        values: list[Any] = [project_id]
        if context_version is not None:
            conditions.append("context_version=?")
            values.append(context_version)
        if kind is not None:
            conditions.append("kind=?")
            values.append(kind)
        values.append(limit)
        with self.connection() as wrapped:
            db = wrapped.db
            rows = db.execute(f"SELECT * FROM artifacts WHERE {' AND '.join(conditions)} ORDER BY created_at DESC LIMIT ?", values).fetchall()
            return [self._manifest(db, row) for row in rows]

    def get_content(self, artifact_id: str, revision: int | None = None) -> dict[str, Any]:
        manifest = self.get_artifact(artifact_id)
        selected = revision if revision is not None else manifest["content_revision"]
        with self.connection() as wrapped:
            row = wrapped.db.execute("SELECT content,created_at FROM artifact_revisions WHERE artifact_id=? AND revision=?",
                                     (artifact_id, selected)).fetchone()
        if not row:
            raise IntelligenceError("ARTIFACT_REVISION_NOT_FOUND", "This content revision does not exist.", 404)
        return {"artifact_id": artifact_id, "kind": manifest["kind"], "content_revision": selected,
                "created_at": row["created_at"], "content": json.loads(row["content"])}

    def update_content(self, artifact_id: str, base_revision: int, content: dict[str, Any]) -> dict[str, Any]:
        now = utc_stamp()
        with self.connection() as wrapped:
            db = wrapped.db
            db.execute("BEGIN IMMEDIATE")
            row = db.execute("SELECT * FROM artifacts WHERE id=?", (artifact_id,)).fetchone()
            if not row:
                raise IntelligenceError("ARTIFACT_NOT_FOUND", "This generated artifact does not exist.", 404)
            actual = row["content_revision"]
            if actual != base_revision:
                raise IntelligenceError("ARTIFACT_REVISION_CONFLICT", "This artifact has a newer content revision.", 409,
                                        details={"expected": base_revision, "actual": actual})
            revision = actual + 1
            db.execute("INSERT INTO artifact_revisions VALUES (?,?,?,?)",
                       (artifact_id, revision, canonical(content), now))
            db.execute("UPDATE artifacts SET content_revision=?,updated_at=? WHERE id=?", (revision, now, artifact_id))
        return {"artifact_id": artifact_id, "content_revision": revision, "validation_findings": []}

    def register_render(self, artifact_id: str, revision: int, file: dict[str, Any], job_id: str | None = None) -> str:
        with self.connection() as wrapped:
            db = wrapped.db
            row = db.execute("SELECT context_version,content_revision FROM artifacts WHERE id=?", (artifact_id,)).fetchone()
            if not row:
                raise IntelligenceError("ARTIFACT_NOT_FOUND", "This generated artifact does not exist.", 404)
            if revision > row["content_revision"]:
                raise IntelligenceError("ARTIFACT_REVISION_NOT_FOUND", "This content revision does not exist.", 404)
            return self._register_file(db, artifact_id, row["context_version"], revision, file, job_id)

    def get_file(self, file_id: str) -> tuple[dict[str, Any], bytes]:
        with self.connection() as wrapped:
            row = wrapped.db.execute("SELECT * FROM artifact_files WHERE id=?", (file_id,)).fetchone()
        if not row:
            raise IntelligenceError("FILE_NOT_FOUND", "This download does not exist.", 404)
        path = (self.file_root / row["storage_name"]).resolve()
        if path.parent != self.file_root or not path.is_file():
            raise IntelligenceError("FILE_NOT_FOUND", "This download is no longer available.", 404)
        return self._file_record(row), path.read_bytes()

    def get_context_reference(self, artifact_id: str) -> dict[str, Any]:
        manifest = self.get_artifact(artifact_id)
        return {"project_id": manifest["project_id"], "context_version": manifest["context_version"],
                "context_hash": manifest["context_hash"]}


class _Connection:
    """Tiny context manager keeping SQL writes transactional."""

    def __init__(self, db: sqlite3.Connection):
        self.db = db

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.db.rollback()
            else:
                self.db.commit()
        finally:
            self.db.close()
